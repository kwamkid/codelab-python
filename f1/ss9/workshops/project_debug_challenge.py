# 🎯 "เครื่องคิดเงินทอน" นี้มี bug — ใช้ Debugger หา + แก้ให้รันได้
#    รวมทุก error: NameError, TypeError, Logic bug
# ───────────────────────────────────────────────────────────

print("💰 เครื่องคิดเงินทอน")

price = int(input("ราคาสินค้า: "))
paid = int(input("จ่ายมา: "))

# 🐛 BUG 1 — TypeError: ลืมว่า input เป็น str (แก้แล้วด้านบนด้วย int())
change = paid - price

# 🐛 BUG 2 — Logic: เงื่อนไขกลับด้าน (ต้อง >= ไม่ใช่ <)
if paid >= price:           # 👈 จ่ายพอ = paid มากกว่าหรือเท่าราคา
    print(f"เงินทอน: {change} บาท")
else:
    # 🐛 BUG 3 — NameError: ใช้ตัวแปรให้ตรงชื่อ
    short = price - paid
    print(f"เงินไม่พอ ขาด {____} บาท")    # 👈 แก้: short

