friends = ["น้องเอิน", "น้องปอ", "น้องปุย", "น้องต้น", "น้องข้าว"]

# คนแรก = index 0
print("👦 คนแรก:", friends[0])

# คนสุดท้าย = -1 (ไม่ต้องนับจำนวน)
print("👧 คนสุดท้าย:", friends[-1])

# โบนัส: คนกลาง (5 คน → index 2)
print("😎 คนกลาง:", friends[2])

# Output:
# 👦 คนแรก: น้องเอิน
# 👧 คนสุดท้าย: น้องข้าว
# 😎 คนกลาง: น้องปุย
