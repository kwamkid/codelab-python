lunch = [
    "ข้าวหมูแดง",    # index 0 = จันทร์
    "ก๋วยเตี๋ยว",     # index 1 = อังคาร
    "ข้าวมันไก่",     # index 2 = พุธ ← แก้ตรงนี้
    "ผัดกะเพรา",      # index 3 = พฤหัส
    "ก๋วยจั๊บ",       # index 4 = ศุกร์
]

print("เมนูก่อนแก้:", lunch)

# วันพุธ = index 2
lunch[2] = "ข้าวผัดปู"

print("เมนูหลังแก้:", lunch)

# โบนัส: แก้เมนูวันศุกร์ด้วย -1
new_friday = input("เพื่อนอยากกินอะไรวันศุกร์? ")
lunch[-1] = new_friday
print("เมนูสุดท้าย:", lunch)
